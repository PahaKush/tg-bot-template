from enum import StrEnum


class Access(StrEnum):
    """Кто имеет право нажать этот коллбэк.

    Разметка ОБЯЗАТЕЛЬНА для каждого CallbackData, и неразмеченный коллбэк отвергается
    мидлварью (deny-by-default). Причина жёсткости: при неявном правиле («проверим, если
    у коллбэка окажется нужное поле») новый коллбэк молча остаётся без проверки, и об
    этом узнают не из кода, а из последствий.

    tests/test_callback_access.py не даёт добавить коллбэк без разметки.
    """

    PUBLIC = "public"  # доступно всем, включая незнакомых
    USER = "user"  # любой пользователь бота
    ADMIN = "admin"  # только ADMIN_IDS
    HANDLER = "handler"  # проверку делает сам хендлер — осознанный opt-out

    # Владение конкретным ресурсом (заметка, заказ, проект) НАМЕРЕННО не уровень доступа.
    # Его нельзя проверить в мидлвари, не зная предметной области, а главное — проверка
    # одного идентификатора создаёт ложное чувство защищённости: соседний id уходит в SQL
    # без скоупа. Скоуп владения живёт в SQL каждого запроса — см. NotesRepository.


class NoteColor(StrEnum):
    """Пример доменного StrEnum: значение читаемо в БД и в callback_data."""

    DEFAULT = "default"
    IMPORTANT = "important"
    DONE = "done"

    @property
    def icon(self) -> str:
        return {"default": "📄", "important": "❗", "done": "✅"}[self.value]
